// Copies registry/providers.json into the package as the bundled registry.
//
// Run from the repository root after editing the registry:
//
//   dart run tool/sync_registry.dart
import 'dart:convert';
import 'dart:io';

const _source = 'registry/providers.json';
const _target = 'packages/upcloud/lib/src/registry/bundled_registry_data.dart';

void main() {
  final json = File(_source).readAsStringSync();
  // Validates the JSON before bundling it.
  jsonDecode(json);
  File(_target).writeAsStringSync(render(json));
  stdout.writeln('Bundled $_source into $_target');
}

/// Dart source embedding [json].
String render(String json) {
  if (json.contains("'''")) {
    throw const FormatException("The registry cannot contain '''");
  }
  return '''
// GENERATED by tool/sync_registry.dart from registry/providers.json.
// Do not edit: edit the JSON and run `dart run tool/sync_registry.dart`.

/// Contents of `registry/providers.json` at release time.
const bundledRegistryJson = r\'\'\'
$json\'\'\';
''';
}
